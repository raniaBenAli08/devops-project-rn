interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (text: string) => string;
}

const LocaleContext = createContext<LocaleContextValue | undefined>(undefined);

const getInitialLocale = (): Locale => {
  const savedLocale = window.localStorage.getItem('hr-admin-locale');
  return savedLocale === 'fr' ? 'fr' : 'en';
};

export const LocaleProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = locale === 'fr' ? 'HR Admin | Gestion des ressources humaines' : 'HR Admin | People operations';
  }, [locale]);

  const setLocale = (nextLocale: Locale) => {
    window.localStorage.setItem('hr-admin-locale', nextLocale);
    setLocaleState(nextLocale);
  };

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (text: string) => translations[locale][text] || text,
    }),
    [locale],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
};

export const useLocale = (): LocaleContextValue => {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error('useLocale must be used within a LocaleProvider');
  }
  return context;
};
